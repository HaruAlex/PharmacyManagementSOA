package repositories;

import org.junit.Before;
import play.Application;
import play.db.Database;
import play.inject.guice.GuiceApplicationBuilder;
import play.test.WithApplication;

import java.sql.Connection;
import java.sql.Statement;
import java.util.concurrent.atomic.AtomicLong;

/**
 * Starts each repository/controller test against an isolated H2 database whose
 * Catalog tables mirror the columns used by docs/database/01_create_tables.sql.
 */
public abstract class CatalogTestSupport extends WithApplication {
    private static final AtomicLong DATABASE_SEQUENCE = new AtomicLong();

    protected Database database;

    @Override
    protected Application provideApplication() {
        String databaseName = "catalog_test_" + DATABASE_SEQUENCE.incrementAndGet();
        return new GuiceApplicationBuilder()
                .configure("db.default.driver", "org.h2.Driver")
                .configure("db.default.url", "jdbc:h2:mem:" + databaseName + ";MODE=MSSQLServer;DB_CLOSE_DELAY=-1")
                .configure("db.default.username", "sa")
                .configure("db.default.password", "")
                .build();
    }

    @Before
    public void createCatalogSchema() {
        database = app.injector().instanceOf(Database.class);
        database.withConnection(connection -> {
            try (Statement statement = connection.createStatement()) {
                for (String ddl : schemaStatements()) {
                    statement.execute(ddl);
                }
            }
            return null;
        });
    }

    private String[] schemaStatements() {
        return new String[] {
                "CREATE SCHEMA catalog",
                "CREATE SCHEMA sales",
                "CREATE TABLE catalog.Branches (" +
                        "BranchId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, BranchCode VARCHAR(20) NOT NULL UNIQUE, " +
                        "BranchName VARCHAR(150) NOT NULL, Address VARCHAR(250), Phone VARCHAR(20), " +
                        "BranchType VARCHAR(20) NOT NULL CHECK (BranchType IN ('CENTRAL_WAREHOUSE','PHARMACY')), " +
                        "LicenseNumber VARCHAR(100), LicenseExpiry DATE, " +
                        "IsActive BOOLEAN NOT NULL DEFAULT TRUE)",
                "CREATE TABLE catalog.DrugGroups (" +
                        "DrugGroupId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, GroupCode VARCHAR(30) NOT NULL UNIQUE, " +
                        "GroupName VARCHAR(120) NOT NULL UNIQUE, Description VARCHAR(300), ParentDrugGroupId INT, " +
                        "Level INT NOT NULL DEFAULT 0, Path VARCHAR(500), DisplayOrder INT NOT NULL DEFAULT 0, " +
                        "IsActive BOOLEAN NOT NULL DEFAULT TRUE, " +
                        "FOREIGN KEY (ParentDrugGroupId) REFERENCES catalog.DrugGroups(DrugGroupId))",
                "CREATE TABLE catalog.Manufacturers (" +
                        "ManufacturerId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                        "ManufacturerName VARCHAR(150) NOT NULL UNIQUE, Country VARCHAR(80), IsActive BOOLEAN NOT NULL DEFAULT TRUE)",
                "CREATE TABLE catalog.Units (" +
                        "UnitId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, UnitName VARCHAR(50) NOT NULL UNIQUE, " +
                        "UnitCode VARCHAR(20) NOT NULL UNIQUE, Description VARCHAR(300), IsActive BOOLEAN NOT NULL DEFAULT TRUE)",
                "CREATE TABLE catalog.Suppliers (" +
                        "SupplierId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, SupplierCode VARCHAR(30) NOT NULL UNIQUE, " +
                        "SupplierName VARCHAR(180) NOT NULL, Phone VARCHAR(20), Email VARCHAR(150), " +
                        "Address VARCHAR(250), TaxCode VARCHAR(30), ContactPerson VARCHAR(100), ContactPhone VARCHAR(30), " +
                        "PaymentTermDays INT NOT NULL DEFAULT 0, IsActive BOOLEAN NOT NULL DEFAULT TRUE)",
                "CREATE TABLE catalog.Customers (" +
                        "CustomerId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, CustomerCode VARCHAR(30) NOT NULL UNIQUE, " +
                        "CustomerName VARCHAR(150) NOT NULL, Phone VARCHAR(20) UNIQUE, Email VARCHAR(150), " +
                        "LoyaltyPoints INT NOT NULL DEFAULT 0 CHECK (LoyaltyPoints >= 0), Allergies VARCHAR(1000), " +
                        "IsActive BOOLEAN NOT NULL DEFAULT TRUE)",
                "CREATE TABLE catalog.Drugs (" +
                        "DrugId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, DrugCode VARCHAR(30) NOT NULL UNIQUE, " +
                        "Barcode VARCHAR(50) UNIQUE, DrugName VARCHAR(200) NOT NULL, ActiveIngredient VARCHAR(200), " +
                        "Concentration VARCHAR(100), DosageForm VARCHAR(100), StorageCondition VARCHAR(500), " +
                        "DrugType VARCHAR(20) NOT NULL DEFAULT 'OTC', DrugGroupId INT NOT NULL, " +
                        "ManufacturerId INT NOT NULL, BaseUnitId INT NOT NULL, " +
                        "PrescriptionRequired BOOLEAN NOT NULL DEFAULT FALSE, ControlledDrug BOOLEAN NOT NULL DEFAULT FALSE, " +
                        "RegistrationNumber VARCHAR(60), Description VARCHAR(500), IsActive BOOLEAN NOT NULL DEFAULT TRUE, " +
                        "FOREIGN KEY (DrugGroupId) REFERENCES catalog.DrugGroups(DrugGroupId), " +
                        "FOREIGN KEY (ManufacturerId) REFERENCES catalog.Manufacturers(ManufacturerId), " +
                        "FOREIGN KEY (BaseUnitId) REFERENCES catalog.Units(UnitId))",
                "CREATE TABLE catalog.DrugUnitConversions (" +
                        "ConversionId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, DrugId INT NOT NULL, UnitId INT NOT NULL, " +
                        "ConversionToBase DECIMAL(18,4) NOT NULL, IsSaleUnit BOOLEAN NOT NULL DEFAULT TRUE, " +
                        "SalePrice DECIMAL(18,2), IsDefault BOOLEAN NOT NULL DEFAULT FALSE, " +
                        "FOREIGN KEY (DrugId) REFERENCES catalog.Drugs(DrugId), FOREIGN KEY (UnitId) REFERENCES catalog.Units(UnitId))",
                "CREATE TABLE sales.Invoices (InvoiceId BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, CustomerId INT)",
                "CREATE TABLE sales.Prescriptions (PrescriptionId BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, CustomerId INT)"
        };
    }

    protected void execute(String sql) {
        database.withConnection(connection -> {
            try (Statement statement = connection.createStatement()) {
                statement.execute(sql);
            }
            return null;
        });
    }

    protected long scalarLong(String sql) {
        return database.withConnection(connection -> {
            try (Statement statement = connection.createStatement();
                 java.sql.ResultSet rows = statement.executeQuery(sql)) {
                rows.next();
                return rows.getLong(1);
            }
        });
    }
}
